create extension if not exists pg_trgm;

create table if not exists users (
  id               bigint generated by default as identity primary key,
  email            text not null,
  password_hash    text not null,
  role             text not null default 'customer',
  first_name       text not null default '',
  last_name        text not null default '',
  patronymic       text not null default '',
  phone            text not null default '',
  city             text not null default '',
  branch           text not null default '',
  delivery_method  text not null default '',
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  last_login_at    timestamptz
);
create unique index if not exists users_email_uq on users (lower(email));

create table if not exists categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  parent_id   bigint references categories(id) on delete cascade,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);
create unique index if not exists categories_parent_name_uq on categories ((coalesce(parent_id, 0)), name);
create index if not exists categories_parent_idx on categories (parent_id);

create table if not exists products (
  id                 bigint generated by default as identity primary key,
  title              text not null default '',
  short_description  text not null default '',
  description        text not null default '',
  price              numeric(12,2) not null default 0,
  stock              integer not null default 0,
  availability       text not null default 'in_stock',
  category           text not null default '',
  category_id        bigint references categories(id) on delete set null,
  brand              text not null default '',
  featured           boolean not null default false,
  active             boolean not null default true,
  images             jsonb not null default '[]'::jsonb,
  specs              jsonb not null default '{}'::jsonb,
  sections           jsonb not null default '[]'::jsonb,
  tags               jsonb not null default '[]'::jsonb,
  article            text not null default '',
  weight             numeric(10,3),
  length             numeric(10,2),
  width              numeric(10,2),
  height             numeric(10,2),
  search_text        text not null default '',
  supplier_id        bigint,
  supplier_url       text,
  supplier_price     numeric(12,2),
  sync_locked        boolean not null default false,
  synced_at          timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

alter table products add column if not exists availability   text not null default 'in_stock';
alter table products add column if not exists brand          text not null default '';
alter table products add column if not exists active         boolean not null default true;
alter table products add column if not exists search_text    text not null default '';
alter table products add column if not exists supplier_id    bigint;
alter table products add column if not exists supplier_url   text;
alter table products add column if not exists supplier_price numeric(12,2);
alter table products add column if not exists sync_locked    boolean not null default false;
alter table products add column if not exists synced_at      timestamptz;
alter table products add column if not exists price_unit     text not null default '';
alter table products add column if not exists price_from     boolean not null default false;

create unique index if not exists products_supplier_id_uq on products (supplier_id);
create index if not exists products_category_idx   on products (category_id) where active;
create index if not exists products_created_idx    on products (id desc) where active;
create index if not exists products_price_idx      on products (price) where active;
create index if not exists products_brand_idx      on products (brand) where active;
create index if not exists products_featured_idx   on products (id) where active and featured;
create index if not exists products_search_trgm    on products using gin (search_text gin_trgm_ops);

create table if not exists orders (
  id                   bigint generated by default as identity primary key,
  created_at           timestamptz not null default now(),
  user_id              bigint references users(id) on delete set null,
  customer_first_name  text not null default '',
  customer_last_name   text not null default '',
  customer_patronymic  text not null default '',
  customer_email       text,
  customer_phone       text,
  delivery_method      text not null default 'Нова Пошта',
  delivery_city        text,
  delivery_branch      text,
  do_not_call          boolean not null default false,
  comment              text not null default '',
  total_amount         numeric(12,2) not null default 0,
  status               text not null default 'Нове',
  payment_method       text,
  payment_status       text,
  payment_invoice_id   text,
  payment_metadata     jsonb,
  items                jsonb not null default '[]'::jsonb
);
create index if not exists orders_created_idx on orders (created_at desc);
create index if not exists orders_user_idx    on orders (user_id);
create index if not exists orders_email_idx   on orders (lower(customer_email));

create table if not exists support_requests (
  id                   bigint generated by default as identity primary key,
  created_at           timestamptz not null default now(),
  user_id              bigint references users(id) on delete set null,
  customer_first_name  text,
  customer_last_name   text,
  customer_email       text,
  customer_phone       text,
  message              text,
  status               text not null default 'Нове'
);
create index if not exists support_email_idx on support_requests (lower(customer_email));

